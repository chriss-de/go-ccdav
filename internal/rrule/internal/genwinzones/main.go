// Command genwinzones generates windowszones.go (Windows time zone name to
// IANA mapping) from the CLDR windowsZones.xml, using the territory "001"
// (default) entries. It also records the "(UTC+01:00) Amsterdam, ..."
// display names found in the comments, which some Outlook versions send as
// TZID.
//
// Usage (from internal/rrule):
//
//	go run ./internal/genwinzones [-in windowsZones.xml] [-o windowszones.go]
//
// Without -in the file is downloaded from the CLDR GitHub repository.
package main

import (
	"bytes"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strings"
)

const defaultURL = "https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml"

func main() {
	in := flag.String("in", "", "local windowsZones.xml (default: download from CLDR)")
	out := flag.String("o", "windowszones.go", "output file")
	flag.Parse()

	var data []byte
	var err error
	source := defaultURL
	if *in != "" {
		source = *in
		data, err = os.ReadFile(*in)
	} else {
		data, err = fetch(defaultURL)
	}
	if err != nil {
		log.Fatal(err)
	}
	names, display, version, err := parse(data)
	if err != nil {
		log.Fatal(err)
	}
	if len(names) < 100 {
		log.Fatalf("only %d zones found", len(names))
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/genwinzones from CLDR windowsZones.xml (typeVersion %s); DO NOT EDIT.\n\n", version)
	fmt.Fprintf(&b, "package rrule\n\n")
	fmt.Fprintf(&b, "// windowsZones maps Windows time zone names to IANA names (CLDR territory 001).\n")
	fmt.Fprintf(&b, "var windowsZones = map[string]string{\n")
	for _, k := range sortedKeys(names) {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, names[k])
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "// windowsDisplayZones maps Windows display names, as found in the CLDR\n// comments, to IANA names.\n")
	fmt.Fprintf(&b, "var windowsDisplayZones = map[string]string{\n")
	for _, k := range sortedKeys(display) {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, display[k])
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s: %d zones, %d display names from %s", *out, len(names), len(display), source)
}

func fetch(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// parse walks the XML token stream so that comments preceding a mapZone
// group (the Windows display name) can be associated with it.
func parse(data []byte) (names, display map[string]string, version string, err error) {
	names = map[string]string{}
	display = map[string]string{}
	dec := xml.NewDecoder(bytes.NewReader(data))
	dec.Strict = false
	var lastComment string
	for {
		tok, err := dec.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, nil, "", err
		}
		switch t := tok.(type) {
		case xml.Comment:
			lastComment = strings.TrimSpace(string(t))
		case xml.StartElement:
			attr := func(n string) string {
				for _, a := range t.Attr {
					if a.Name.Local == n {
						return a.Value
					}
				}
				return ""
			}
			switch t.Name.Local {
			case "mapTimezones":
				version = attr("typeVersion")
			case "mapZone":
				if attr("territory") != "001" {
					continue
				}
				// The type attribute may list several zones; the first is canonical.
				iana := strings.Fields(attr("type"))[0]
				names[attr("other")] = iana
				if strings.HasPrefix(lastComment, "(UTC") {
					display[lastComment] = iana
				}
				lastComment = ""
			}
		}
	}
	return names, display, version, nil
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
