// Package store keeps calendars and address books as plain files:
//
//	<root>/users/<user>/<kind>/<collection>/
//	    .meta.json     collection properties
//	    .changes.log   append-only "<token> <PUT|DEL> <name>" lines
//	    <name>         object resources (.ics / .vcf), stored byte-exact
//
// Every collection has its own RWMutex and an in-memory index (ETag, UID,
// size, mtime) built on first use.
package store

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"sync"
	"sync/atomic"
	"time"
)

type Kind string

const (
	Calendars    Kind = "calendars"
	AddressBooks Kind = "addressbooks"
)

var (
	ErrNotFound     = errors.New("store: not found")
	ErrExists       = errors.New("store: already exists")
	ErrPrecondition = errors.New("store: precondition failed")
	ErrBadName      = errors.New("store: invalid name")
	ErrReadOnly     = errors.New("store: read-only collection")
	ErrTooLarge     = errors.New("store: too large")
	ErrQuota        = errors.New("store: storage quota exceeded")
)

// UIDConflictError is returned by Put when another object in the collection
// already uses the UID.
type UIDConflictError struct{ Existing string }

func (e *UIDConflictError) Error() string { return "store: UID already used by " + e.Existing }

// Meta holds collection properties, persisted as .meta.json.
type Meta struct {
	DisplayName string   `json:"displayname,omitempty"`
	Description string   `json:"description,omitempty"`
	Color       string   `json:"color,omitempty"`
	Order       string   `json:"order,omitempty"`
	Timezone    string   `json:"timezone,omitempty"`   // VCALENDAR text with one VTIMEZONE
	Components  []string `json:"components,omitempty"` // VEVENT, VTODO, VJOURNAL
	SyncID      string   `json:"sync_id,omitempty"`    // see Collection.SyncID
	Shares      []Share  `json:"shares,omitempty"`
	// ReadOnly collections are generated by the server (the directory
	// address book); clients and the UI can't change or share them.
	ReadOnly bool `json:"read_only,omitempty"`
	// Unsubscribed is the owner's JMAP isSubscribed=false; DAV ignores it.
	Unsubscribed bool `json:"unsubscribed,omitempty"`
	// JMAP calendar settings, which DAV doesn't know: isVisible=false,
	// includeInAvailability ("" = "all") and default alerts (JSON).
	Invisible                bool            `json:"invisible,omitempty"`
	Availability             string          `json:"availability,omitempty"`
	DefaultAlertsWithTime    json.RawMessage `json:"default_alerts_with_time,omitempty"`
	DefaultAlertsWithoutTime json.RawMessage `json:"default_alerts_without_time,omitempty"`
	// DeadProps stores unknown PROPPATCHed properties: "{ns}local" -> inner XML.
	DeadProps map[string]string `json:"dead_props,omitempty"`
}

// ObjectInfo describes one stored object.
type ObjectInfo struct {
	Name    string
	ETag    string // quoted
	UID     string
	Comp    string // calendar component type (VEVENT, VTODO, ...); "" for vCards
	Size    int64
	ModTime time.Time
}

// UIDFunc extracts the UID and, for calendar objects, the component type
// from an object body; "" if none.
type UIDFunc func(kind Kind, data []byte) (uid, comp string)

type Store struct {
	root  string
	uidOf UIDFunc

	mu       sync.Mutex
	cols     map[string]*Collection
	track    bool // account logs on (TrackAccounts)
	onChange func(owner string, kind Kind)
	accts    map[string]*Account // "<owner>/<kind>"

	prefs prefsStore
	over  overlays

	broken map[string]error // collections that failed to load, by key (Broken)

	quota atomic.Pointer[func() int64] // per-user bytes, 0 = none (SetQuota)
	used  map[string]*atomic.Int64     // owner -> bytes of their loaded collections
}

func (s *Store) markBroken(key string, err error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.broken == nil {
		s.broken = map[string]error{}
	}
	s.broken[key] = err
}

// Broken returns the collections that could not be loaded (by key, with
// the reason) and forgets them, so that each is reported once per load.
// They are left out of listings until fixed on disk.
func (s *Store) Broken() map[string]error {
	s.mu.Lock()
	defer s.mu.Unlock()
	b := s.broken
	s.broken = nil
	return b
}

// SetQuota sets how many bytes of objects each user may own; q is asked
// on every write (0 = no limit). Writes to a shared collection count for
// its owner; generated (read-only) collections don't count.
func (s *Store) SetQuota(q func() int64) { s.quota.Store(&q) }

// quotaNow is the current quota; collections call it under their lock,
// so it takes none.
func (s *Store) quotaNow() int64 {
	if q := s.quota.Load(); q != nil {
		return (*q)()
	}
	return 0
}

// usedBy returns owner's usage counter; the caller holds s.mu.
func (s *Store) usedBy(owner string) *atomic.Int64 {
	if s.used == nil {
		s.used = map[string]*atomic.Int64{}
	}
	u := s.used[owner]
	if u == nil {
		u = new(atomic.Int64)
		s.used[owner] = u
	}
	return u
}

func New(root string, uidOf UIDFunc) *Store {
	return &Store{root: root, uidOf: uidOf, cols: make(map[string]*Collection)}
}

// ValidName reports whether name is usable as a collection or object name.
func ValidName(name string) bool {
	if name == "" || len(name) > 255 || name[0] == '.' {
		return false
	}
	for _, r := range name {
		if r < 0x20 || r == 0x7f || r == '/' || r == '\\' {
			return false
		}
	}
	return true
}

// validHome reports whether owner and kind can be used as path segments:
// a plain name and one of the two kinds, so nothing escapes users/.
func validHome(owner string, kind Kind) bool {
	return ValidName(owner) && (kind == Calendars || kind == AddressBooks)
}

func (s *Store) homeDir(owner string, kind Kind) string {
	return filepath.Join(s.root, "users", owner, string(kind))
}

// ValidCollectionName is ValidName for new collections: "~" is reserved
// for the aliases of shared collections ("<owner>~<name>").
func ValidCollectionName(name string) bool {
	return ValidName(name) && !strings.Contains(name, "~")
}

// EnsureHome creates the home directory if needed. When it did not exist
// yet, the given default collections are created in it.
func (s *Store) EnsureHome(owner string, kind Kind, defaults map[string]Meta) error {
	if !validHome(owner, kind) {
		return ErrBadName
	}
	dir := s.homeDir(owner, kind)
	if _, err := os.Stat(dir); err == nil {
		return nil
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	for name, m := range defaults {
		if _, err := s.CreateCollection(owner, kind, name, m); err != nil && !errors.Is(err, ErrExists) {
			return err
		}
	}
	return nil
}

// Collections lists the owner's collections of a kind, sorted by name.
func (s *Store) Collections(owner string, kind Kind) ([]*Collection, error) {
	if !validHome(owner, kind) {
		return nil, ErrNotFound
	}
	ents, err := os.ReadDir(s.homeDir(owner, kind))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var out []*Collection
	for _, e := range ents {
		if !e.IsDir() || !ValidName(e.Name()) {
			continue
		}
		c, err := s.Collection(owner, kind, e.Name())
		if errors.Is(err, ErrNotFound) {
			continue // deleted since the directory was read
		}
		if err != nil {
			// One unreadable collection (a corrupt .meta.json) must not
			// take the others down; Broken reports it.
			s.markBroken(owner+"/"+string(kind)+"/"+e.Name(), err)
			continue
		}
		out = append(out, c)
	}
	return out, nil
}

// Collection returns a loaded collection or ErrNotFound.
func (s *Store) Collection(owner string, kind Kind, name string) (*Collection, error) {
	if !ValidName(name) || !validHome(owner, kind) {
		return nil, ErrNotFound
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.collectionLocked(owner, kind, name)
}

// collectionLocked is Collection; the caller holds s.mu.
func (s *Store) collectionLocked(owner string, kind Kind, name string) (*Collection, error) {
	key := owner + "/" + string(kind) + "/" + name
	if c, ok := s.cols[key]; ok && !c.gone.Load() {
		return c, nil
	}
	// Not loaded, or deleted (its directory is gone then, unless a new
	// collection was created under the name): load what is on disk.
	delete(s.cols, key)
	c := &Collection{
		Owner: owner, Kind: kind, Name: name,
		dir:   filepath.Join(s.homeDir(owner, kind), name),
		uidOf: s.uidOf,
		used:  s.usedBy(owner),
		quota: s.quotaNow,
	}
	if err := c.load(); err != nil {
		return nil, err
	}
	if !c.meta.ReadOnly { // generated collections don't count (reserve)
		c.used.Add(c.bytes)
	}
	if s.track {
		a, err := s.account(owner, kind)
		if err != nil {
			return nil, err
		}
		c.acct = a
	}
	s.cols[key] = c
	return c, nil
}

// CreateCollection makes a new collection.
func (s *Store) CreateCollection(owner string, kind Kind, name string, m Meta) (*Collection, error) {
	if !ValidCollectionName(name) || !validHome(owner, kind) {
		return nil, ErrBadName
	}
	dir := filepath.Join(s.homeDir(owner, kind), name)
	// Under s.mu until the collection is complete: a lookup (a listing of
	// the home) must not load the directory before .meta.json is there.
	s.mu.Lock()
	c, err := func() (*Collection, error) {
		if err := os.MkdirAll(filepath.Dir(dir), 0o750); err != nil {
			return nil, err
		}
		if err := os.Mkdir(dir, 0o750); err != nil {
			if errors.Is(err, fs.ErrExist) {
				return nil, ErrExists
			}
			return nil, err
		}
		m.SyncID = newSyncID()
		b, _ := json.MarshalIndent(m, "", "  ")
		if err := writeFileAtomic(filepath.Join(dir, ".meta.json"), b); err != nil {
			os.RemoveAll(dir)
			return nil, err
		}
		return s.collectionLocked(owner, kind, name)
	}()
	s.mu.Unlock()
	if err != nil {
		return nil, err
	}
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c, c.acct.noteCollection(c)
}

// DeleteCollection removes a collection and all its objects.
// The collection stays in the cache, marked gone, until its directory is
// removed: a lookup in between must not load it from disk again. If the
// removal fails, nothing changes in memory.
func (s *Store) DeleteCollection(c *Collection) error {
	c.mu.Lock()
	if c.deleted {
		c.mu.Unlock()
		return ErrNotFound
	}
	if err := os.RemoveAll(c.dir); err != nil {
		c.mu.Unlock()
		return err
	}
	c.deleted = true
	c.gone.Store(true)
	c.reserve(-c.bytes)
	c.bytes = 0
	err := c.acct.noteCollectionDeleted(c)
	c.mu.Unlock()
	key := c.Owner + "/" + string(c.Kind) + "/" + c.Name
	s.mu.Lock()
	if s.cols[key] == c {
		delete(s.cols, key)
	}
	s.mu.Unlock()
	return err
}

// Collection is one calendar or address book.
type Collection struct {
	Owner string
	Kind  Kind
	Name  string

	dir   string
	uidOf UIDFunc

	mu       sync.RWMutex
	meta     Meta
	objs     map[string]ObjectInfo
	uids     map[string]string // UID -> object name
	token    uint64
	floor    uint64 // sync tokens below this were compacted away
	logLines int
	deleted  bool
	gone     atomic.Bool // deleted, readable without mu (Store.Collection)
	acct     *Account    // nil unless the store tracks accounts

	bytes int64         // size of the objects
	used  *atomic.Int64 // the owner's bytes, shared by their collections
	quota func() int64  // the store's quotaNow
}

func (c *Collection) load() error {
	b, err := os.ReadFile(filepath.Join(c.dir, ".meta.json"))
	if errors.Is(err, fs.ErrNotExist) {
		if _, err := os.Stat(c.dir); err != nil {
			return ErrNotFound
		}
	} else if err != nil {
		return err
	} else if err := json.Unmarshal(b, &c.meta); err != nil {
		return fmt.Errorf("%s: %w", c.dir, err)
	}
	c.objs = make(map[string]ObjectInfo)
	c.uids = make(map[string]string)
	mtimes := map[string]time.Time{}
	ents, err := os.ReadDir(c.dir)
	if err != nil {
		return err
	}
	for _, e := range ents {
		if strings.HasPrefix(e.Name(), ".tmp-") {
			// Left by a crash in writeFileAtomic. Only old ones: a write
			// may be under way (CreateCollection writes .meta.json).
			if fi, err := e.Info(); err == nil && time.Since(fi.ModTime()) > time.Minute {
				os.Remove(filepath.Join(c.dir, e.Name()))
			}
			continue
		}
		if e.IsDir() || !ValidName(e.Name()) {
			continue
		}
		data, err := os.ReadFile(filepath.Join(c.dir, e.Name()))
		if err != nil {
			return err
		}
		fi, err := e.Info()
		if err != nil {
			return err
		}
		info := c.info(e.Name(), data, fi.ModTime())
		mtimes[info.Name] = fi.ModTime()
		c.objs[info.Name] = info
		c.bytes += info.Size
		if info.UID != "" {
			c.uids[info.UID] = info.Name
		}
	}
	logPath := filepath.Join(c.dir, logName)
	if err := repairLogTail(logPath); err != nil {
		return err
	}
	l, err := readLog(logPath)
	if err != nil {
		return err
	}
	c.token, c.floor, c.logLines = l.last(), l.floor, len(l.entries)
	if err := c.catchUp(l, mtimes, logPath); err != nil {
		return err
	}
	if c.meta.SyncID == "" {
		// Collections from before sync support get an ID once.
		c.meta.SyncID = newSyncID()
		b, _ := json.MarshalIndent(c.meta, "", "  ")
		if err := writeFileAtomic(filepath.Join(c.dir, ".meta.json"), b); err != nil {
			return err
		}
	}
	return nil
}

func (c *Collection) info(name string, data []byte, mod time.Time) ObjectInfo {
	sum := sha256.Sum256(data)
	uid, comp := c.uidOf(c.Kind, data)
	return ObjectInfo{
		Name:    name,
		ETag:    `"` + hex.EncodeToString(sum[:16]) + `"`,
		UID:     uid,
		Comp:    comp,
		Size:    int64(len(data)),
		ModTime: mod.UTC().Truncate(time.Second),
	}
}

// Meta returns a copy of the collection properties.
func (c *Collection) Meta() Meta {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.metaCopy()
}

// ReadOnly reports whether the collection is server-generated.
func (c *Collection) ReadOnly() bool {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.meta.ReadOnly
}

// UpdateMeta applies fn to the properties and persists them. A real
// change bumps the sync token / CTag.
func (c *Collection) UpdateMeta(fn func(*Meta)) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.deleted {
		return ErrNotFound
	}
	// Shares may have been changed on disk by the CLI; don't clobber them.
	if err := c.refreshMeta(); err != nil {
		return err
	}
	m := c.metaCopy()
	fn(&m)
	m.SyncID = c.meta.SyncID
	b, _ := json.MarshalIndent(m, "", "  ")
	if old, _ := json.MarshalIndent(c.meta, "", "  "); bytes.Equal(old, b) {
		return nil
	}
	// Bump the token so clients notice property changes (color, name);
	// logged first, as in Put.
	if err := c.logChange("META", "-"); err != nil {
		return err
	}
	if err := writeFileAtomic(filepath.Join(c.dir, ".meta.json"), b); err != nil {
		return err
	}
	c.meta = m
	return c.acct.noteCollection(c)
}

// metaCopy deep-copies meta; the caller holds the lock.
func (c *Collection) metaCopy() Meta {
	m := c.meta
	m.Components = slices.Clone(m.Components)
	m.DeadProps = maps.Clone(m.DeadProps)
	m.Shares = slices.Clone(m.Shares)
	m.DefaultAlertsWithTime = slices.Clone(m.DefaultAlertsWithTime)
	m.DefaultAlertsWithoutTime = slices.Clone(m.DefaultAlertsWithoutTime)
	return m
}

// SyncToken is the change counter; it doubles as CTag.
func (c *Collection) SyncToken() uint64 {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.token
}

// List returns all objects sorted by name.
func (c *Collection) List() []ObjectInfo {
	c.mu.RLock()
	defer c.mu.RUnlock()
	out := make([]ObjectInfo, 0, len(c.objs))
	for _, o := range c.objs {
		out = append(out, o)
	}
	slices.SortFunc(out, func(a, b ObjectInfo) int { return strings.Compare(a.Name, b.Name) })
	return out
}

// Stat returns the info for one object.
func (c *Collection) Stat(name string) (ObjectInfo, error) {
	c.mu.RLock()
	defer c.mu.RUnlock()
	o, ok := c.objs[name]
	if !ok {
		return ObjectInfo{}, ErrNotFound
	}
	return o, nil
}

// Get reads one object.
func (c *Collection) Get(name string) ([]byte, ObjectInfo, error) {
	c.mu.RLock()
	defer c.mu.RUnlock()
	o, ok := c.objs[name]
	if !ok {
		return nil, ObjectInfo{}, ErrNotFound
	}
	data, err := os.ReadFile(filepath.Join(c.dir, name))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, ObjectInfo{}, ErrNotFound
	}
	return data, o, err
}

// Cond carries HTTP preconditions for writes.
type Cond struct {
	IfMatch     string // ETag that must match, "*" for any existing
	IfNoneMatch string // "*": must not exist; or an ETag that must not match
}

func (c *Collection) check(name string, cond Cond) error {
	o, exists := c.objs[name]
	switch {
	case cond.IfMatch == "*" && !exists,
		cond.IfMatch != "" && cond.IfMatch != "*" && (!exists || !etagIn(o.ETag, cond.IfMatch)),
		cond.IfNoneMatch == "*" && exists,
		cond.IfNoneMatch != "" && cond.IfNoneMatch != "*" && exists && etagIn(o.ETag, cond.IfNoneMatch):
		return ErrPrecondition
	}
	return nil
}

// etagIn checks an ETag against a comma-separated header list, ignoring W/.
func etagIn(etag, list string) bool {
	for t := range strings.SplitSeq(list, ",") {
		t = strings.TrimPrefix(strings.TrimSpace(t), "W/")
		if t == etag || t == "*" {
			return true
		}
	}
	return false
}

// Put stores an object. created reports whether it did not exist before.
func (c *Collection) Put(name string, data []byte, cond Cond) (info ObjectInfo, created bool, err error) {
	if !ValidName(name) {
		return ObjectInfo{}, false, ErrBadName
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.deleted {
		return ObjectInfo{}, false, ErrNotFound
	}
	if err := c.check(name, cond); err != nil {
		return ObjectInfo{}, false, err
	}
	info = c.info(name, data, time.Now())
	if info.UID != "" {
		if other, ok := c.uids[info.UID]; ok && other != name {
			return ObjectInfo{}, false, &UIDConflictError{Existing: other}
		}
	}
	old, existed := c.objs[name]
	grow := info.Size - old.Size
	// Taken from the owner's usage before writing, so that concurrent
	// writes to their other collections can't all pass the check.
	if err := c.reserve(grow); err != nil {
		return ObjectInfo{}, false, err
	}
	// Logged first: a crash in between leaves a logged change that didn't
	// happen (harmless: the client finds the object as it is), never a
	// change sync doesn't report.
	if err := c.logChange("PUT", name); err != nil {
		c.reserve(-grow)
		return ObjectInfo{}, false, err
	}
	if err := writeFileAtomic(filepath.Join(c.dir, name), data); err != nil {
		c.reserve(-grow)
		return ObjectInfo{}, false, err
	}
	c.bytes += grow
	if existed {
		c.dropUID(old.UID, name)
	}
	c.objs[name] = info
	if info.UID != "" {
		c.uids[info.UID] = name
	}
	return info, !existed, c.acct.noteObject(c, info)
}

// Delete removes an object.
func (c *Collection) Delete(name string, cond Cond) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.deleted {
		return ErrNotFound // its directory may belong to a new collection
	}
	o, ok := c.objs[name]
	if !ok {
		return ErrNotFound
	}
	if err := c.check(name, cond); err != nil {
		return err
	}
	if err := c.logChange("DEL", name); err != nil { // first, as in Put
		return err
	}
	if err := os.Remove(filepath.Join(c.dir, name)); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	delete(c.objs, name)
	c.bytes -= o.Size
	c.reserve(-o.Size)
	c.dropUID(o.UID, name)
	return c.acct.noteObjectDeleted(c, name)
}

// Move moves an object to another collection of the same owner and kind,
// keeping its account-log id. Both change logs record it as a deletion
// and a creation, which is what DAV clients need to see.
func (c *Collection) Move(name string, to *Collection, newName string, cond Cond) (ObjectInfo, error) {
	if to == c || to.Owner != c.Owner || to.Kind != c.Kind {
		return ObjectInfo{}, fmt.Errorf("store: can only move between collections of one owner and kind")
	}
	if !ValidName(newName) {
		return ObjectInfo{}, ErrBadName
	}
	first, second := c, to
	if to.Key() < c.Key() {
		first, second = to, c
	}
	first.mu.Lock()
	defer first.mu.Unlock()
	second.mu.Lock()
	defer second.mu.Unlock()
	if c.deleted || to.deleted {
		return ObjectInfo{}, ErrNotFound
	}
	o, ok := c.objs[name]
	if !ok {
		return ObjectInfo{}, ErrNotFound
	}
	if err := c.check(name, cond); err != nil {
		return ObjectInfo{}, err
	}
	if to.meta.ReadOnly {
		return ObjectInfo{}, ErrReadOnly
	}
	if _, exists := to.objs[newName]; exists {
		return ObjectInfo{}, ErrExists
	}
	if other, ok := to.uids[o.UID]; ok && o.UID != "" {
		return ObjectInfo{}, &UIDConflictError{Existing: other}
	}
	data, err := os.ReadFile(filepath.Join(c.dir, name))
	if err != nil {
		return ObjectInfo{}, err
	}
	info := to.info(newName, data, time.Now())
	if err := errors.Join(c.logChange("DEL", name), to.logChange("PUT", newName)); err != nil { // first, as in Put
		return ObjectInfo{}, err
	}
	if err := writeFileAtomic(filepath.Join(to.dir, newName), data); err != nil {
		return ObjectInfo{}, err
	}
	if err := os.Remove(filepath.Join(c.dir, name)); err != nil && !errors.Is(err, fs.ErrNotExist) {
		os.Remove(filepath.Join(to.dir, newName)) // no copy the index doesn't know
		return ObjectInfo{}, err
	}
	delete(c.objs, name)
	c.bytes -= o.Size // same owner: their usage stays
	to.bytes += info.Size
	if o.UID != "" {
		c.dropUID(o.UID, name)
		to.uids[o.UID] = newName
	}
	to.objs[newName] = info
	return info, c.acct.noteMove(c, name, to, info)
}

// dropUID removes name's entry for uid from the UID index. If another
// object has the UID too (files copied by hand), the index then points at
// that one. The caller holds the write lock.
func (c *Collection) dropUID(uid, name string) {
	if uid == "" || c.uids[uid] != name {
		return
	}
	delete(c.uids, uid)
	for n, o := range c.objs {
		if n != name && o.UID == uid {
			c.uids[uid] = n
			return
		}
	}
}

// reserve changes the owner's usage by n bytes; growth fails with ErrQuota
// past the quota. Generated (read-only) collections don't count. The
// caller holds the write lock.
func (c *Collection) reserve(n int64) error {
	if n == 0 || c.meta.ReadOnly {
		return nil
	}
	q := int64(0)
	if n > 0 && c.quota != nil {
		q = c.quota()
	}
	for {
		u := c.used.Load()
		if q > 0 && u+n > q {
			return ErrQuota
		}
		if c.used.CompareAndSwap(u, u+n) {
			return nil
		}
	}
}

// newSyncID gives the collection a new SyncID: old sync tokens become
// invalid and its account-log id changes.
func (c *Collection) newSyncID() error {
	c.mu.Lock()
	defer c.mu.Unlock()
	m := c.metaCopy()
	m.SyncID = newSyncID()
	b, _ := json.MarshalIndent(m, "", "  ")
	if err := writeFileAtomic(filepath.Join(c.dir, ".meta.json"), b); err != nil {
		return err
	}
	c.meta = m
	return nil
}

// ByUID returns the object name holding uid.
func (c *Collection) ByUID(uid string) (string, bool) {
	c.mu.RLock()
	defer c.mu.RUnlock()
	n, ok := c.uids[uid]
	return n, ok
}

func writeFileAtomic(path string, data []byte) error {
	dir := filepath.Dir(path)
	f, err := os.CreateTemp(dir, ".tmp-*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	defer os.Remove(tmp)
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp, 0o640); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		return err
	}
	if d, err := os.Open(dir); err == nil {
		d.Sync()
		d.Close()
	}
	return nil
}
